"""Application-owned structural ports for capture infrastructure."""

from __future__ import annotations

from collections.abc import Callable
from contextlib import AbstractContextManager
from pathlib import Path
from threading import Thread
from typing import Literal, Protocol, runtime_checkable

from ...config import FirmwareObservationConfig, WriterConfig
from ..domain.clock_state import ClockIntent, ClockRange, ClockState
from ..domain.quarantine_machine import QuarantineState
from ..domain.ring_protocol import DoneNotification, ReadBeginNotification, RingInfo


class StorageLeasePort(Protocol):
    """Active storage mutation capability held across a consuming operation."""

    def require_active(self) -> None: ...


type StorageLeaseContext = AbstractContextManager[StorageLeasePort]
type StorageLeaseFactory = Callable[[], StorageLeaseContext]


class AttemptDescriptorShape(Protocol):
    @property
    def attempt_id(self) -> str: ...

    @property
    def start_sequence(self) -> int: ...

    @property
    def packet_count(self) -> int: ...


@runtime_checkable
class DurablePrefixShape(Protocol):
    @property
    def start_sequence(self) -> int: ...

    @property
    def next_sequence(self) -> int: ...

    @property
    def record_count(self) -> int: ...

    @property
    def raw_sha256(self) -> str: ...


@runtime_checkable
class SealResultShape(Protocol):
    @property
    def bundle_path(self) -> Path: ...

    @property
    def deduplicated(self) -> bool: ...


@runtime_checkable
class DurableSealShape(Protocol):
    """Internal SQL custody that is safe to establish before ADVANCE."""

    @property
    def source_id(self) -> str: ...

    @property
    def start_sequence(self) -> int: ...

    @property
    def next_sequence(self) -> int: ...

    @property
    def record_count(self) -> int: ...

    @property
    def raw_sha256(self) -> str: ...


class QuarantineAdmissionShape(DurablePrefixShape, Protocol):
    @property
    def source_id(self) -> str: ...

    @property
    def lifecycle(self) -> str: ...


class SweepResultShape(Protocol):
    @property
    def removed_source_ids(self) -> tuple[str, ...]: ...

    @property
    def progressed(self) -> bool: ...


class PublicationOutcomeShape(Protocol):
    @property
    def state(self) -> str: ...

    @property
    def reason(self) -> str | None: ...

    @property
    def retry_after_seconds(self) -> float | None: ...


class ClockStatePort(Protocol):
    """The one durable active clock projection used by runtime telemetry."""

    def state(self) -> ClockState: ...

    def observe(
        self,
        info: RingInfo,
        *,
        offset_seconds: float,
        uncertainty_seconds: float,
        source_id: str,
        tolerance_seconds: float,
    ) -> ClockState: ...

    def prepare(self, intent: ClockIntent) -> ClockState: ...

    def mark_uncertain(self, operation_id: str, *, write_sequence_after: int | None = None) -> ClockState: ...

    def cancel_prepared(self, operation_id: str) -> ClockState: ...

    def finish(self, operation_id: str, ranges: tuple[ClockRange, ...]) -> ClockState: ...


class RecoveryShape(Protocol):
    @property
    def valid_records(self) -> int: ...

    @property
    def raw_bytes(self) -> int: ...


class StagedAttemptShape(Protocol):
    @property
    def attempt_id(self) -> str: ...

    def recover(self) -> RecoveryShape: ...

    def close(self) -> None: ...


class ResumeAttemptShape(Protocol):
    @property
    def attempt_id(self) -> str: ...

    @property
    def durable_prefix(self) -> DurablePrefixShape: ...

    def close(self) -> None: ...


class StagingWriterTargetPort(Protocol):
    """Synchronous writer target constructed by the storage capability."""

    @property
    def attempt_id(self) -> str: ...

    @property
    def durable_prefix(self) -> DurablePrefixShape: ...

    def prepare(self) -> AttemptDescriptorShape: ...

    def prepare_leg(self, start_sequence: int, record_count: int) -> DurablePrefixShape: ...

    def read_begin(self, notice: ReadBeginNotification) -> None: ...

    def append_chunk(self, offset: int, chunk: memoryview, tail: bytes = b"") -> object: ...

    def checkpoint(self) -> DurablePrefixShape: ...

    def interrupt(self) -> DurablePrefixShape: ...

    def seal(self, done_notice: DoneNotification) -> SealResultShape | DurableSealShape: ...

    def publish_prefix(self) -> SealResultShape | DurableSealShape | None: ...

    def publish_ready(self) -> PublicationOutcomeShape: ...

    def close(self) -> None: ...


class WriterProgressShape(Protocol):
    @property
    def submitted(self) -> int: ...


class BatchWriterPort(Protocol):
    """Asynchronous writer surface needed by opportunistic coordination."""

    @property
    def attempt_id(self) -> str: ...

    @property
    def thread(self) -> Thread: ...

    @property
    def progress(self) -> WriterProgressShape: ...

    @property
    def failure(self) -> BaseException | None: ...

    async def wait_failure(self) -> BaseException: ...

    @property
    def submitted_high_water(self) -> int: ...

    @property
    def written_high_water(self) -> int: ...

    async def start(self) -> None: ...

    @property
    def initial_prefix(self) -> DurablePrefixShape: ...

    @property
    def interrupted_prefix(self) -> DurablePrefixShape | None: ...

    async def prepare_leg(self, start_sequence: int, record_count: int) -> DurablePrefixShape: ...

    async def read_begin(self, notice: ReadBeginNotification) -> object: ...

    async def checkpoint(self) -> DurablePrefixShape: ...

    async def barrier(self) -> DurablePrefixShape: ...

    async def interrupt(self) -> DurablePrefixShape: ...

    async def seal(self, done_notice: DoneNotification) -> SealResultShape | DurableSealShape: ...

    async def await_seal_result(self) -> SealResultShape | DurableSealShape | None: ...

    async def publish_prefix(self) -> SealResultShape | DurableSealShape | None: ...

    async def close(self) -> None: ...

    def publish(self, high_water: int, tail: bytes = b"") -> bool: ...

    def submit_read_begin(self, notice: ReadBeginNotification) -> object: ...


class ObservationWriterPort(Protocol):
    """Best-effort firmware observation sink for one coordinator run."""

    def observe(self, info: RingInfo) -> None: ...

    def close(self) -> None: ...


@runtime_checkable
class StagingPort(Protocol):
    """Synchronous local staging operations used by the coordinator."""

    @property
    def paths(self) -> object: ...

    def clock_mutation_lease(self) -> StorageLeaseContext: ...

    def recover_and_publish(self) -> PublicationOutcomeShape: ...

    def publication_retry_schedule(self) -> tuple[int, float] | None: ...

    def publication_followup_due(self) -> bool: ...

    def publication_wake_admitted(self) -> bool: ...

    def publication_timer_fired(self, generation: int, deadline: float) -> bool: ...

    def publication_capture_begin(self) -> None: ...

    def publication_capture_intent(self) -> None: ...

    def publication_quiesced(self) -> None: ...

    def publication_capture_end(self) -> bool: ...

    def publication_shutdown(self) -> None: ...

    def inspect_recovery(self) -> tuple[bool, bool]: ...

    def append_ready_closure(self, next_sequence: int, reason: str) -> object: ...

    def begin_ready_visit(self) -> object | None: ...

    def require_capture_space(self, record_count: int) -> None: ...

    def record_confirmed_loss(
        self, attempt_id: str, start_sequence: int, end_sequence: int, occurred_at: str
    ) -> str: ...

    def close_orphaned_drafts(self, reason: str, *, drain_cursor: int | None = None) -> object | None: ...

    def close_pending_prefix(
        self, reason: str, *, include_unpublished: bool = True, drain_cursor: int | None = None
    ) -> object | None: ...

    def pending_attempts(self) -> tuple[AttemptDescriptorShape, ...]: ...

    def quarantine_pending(self, reason: str) -> tuple[str, ...]: ...

    def quarantine_attempt_source(self, attempt_id: str) -> str: ...

    def open_attempt(self, attempt_id: str) -> StagedAttemptShape: ...

    def device_lock(self, *, operation: str = "unknown") -> StorageLeaseContext: ...

    def resume_streaming_attempt(self, lease: StorageLeasePort) -> ResumeAttemptShape | None: ...

    def make_staging_writer(self, start: int, count: int) -> StagingWriterTargetPort: ...

    def admit_quarantined_prefix(
        self, source: str, *, should_defer: Callable[[], bool]
    ) -> QuarantineAdmissionShape: ...

    def terminalize_prefix_attempt(self, attempt_id: str) -> None: ...

    def sweep_terminal_quarantine(self, *, should_defer: Callable[[], bool]) -> SweepResultShape: ...

    def refresh_utc_projection(self) -> int: ...

    def quarantined_attempts(self, *, should_defer: Callable[[], bool]) -> tuple[str, ...]: ...

    def quarantine_state(self, source: str) -> QuarantineState: ...

    def mark_quarantine_unprocessable(self, source: str, reason: str) -> None: ...


QuarantineErrorKind = Literal["unprocessable", "deferred", "retryable"]


@runtime_checkable
class CaptureRuntimePort(Protocol):
    """Composition and infrastructure seam injected into the application."""

    def make_batch_writer(  # noqa: PLR0913 - port mirrors bounded writer construction inputs
        self,
        staging: StagingPort,
        start: int,
        count: int,
        *,
        source_start: int,
        source: memoryview,
        config: WriterConfig,
    ) -> BatchWriterPort: ...

    def make_observation_writer(
        self, staging: StagingPort, config: FirmwareObservationConfig, on_error: Callable[[Exception], None]
    ) -> ObservationWriterPort: ...

    def make_clock_state_store(self, staging: StagingPort) -> ClockStatePort: ...

    def admit_quarantined_prefix(
        self,
        source: str,
        staging: StagingPort,
        should_defer: Callable[[], bool],
    ) -> QuarantineAdmissionShape: ...

    def classify_quarantine_error(self, error: BaseException) -> QuarantineErrorKind | None: ...

    def is_writer_error(self, error: BaseException) -> bool: ...

    def is_writer_failed(self, error: BaseException) -> bool: ...

    def is_staging_error(self, error: BaseException) -> bool: ...

    def is_device_busy_error(self, error: BaseException) -> bool: ...

    def debug_event(self, event: str, **fields: object) -> None: ...

    def debug_exception(self, event: str, error: BaseException, **fields: object) -> None: ...
